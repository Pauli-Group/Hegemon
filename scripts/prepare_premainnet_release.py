def adapt_sync_import_release_binding(builds: str) -> str:
    """Route only this preparation successor through additive repair gates."""
    old = "scripts/check_v011_release_successor.py --require-authorized"
    new = "scripts/check_v011_sync_import_successor.py --require-authorized"
    if builds.count(old) != 5:
        raise ValueError("expected one source and four final artifact successor gates")
    builds = builds.replace(old, new)
    old_scope = (
        "scripts/tests/v011_current_successor/test_successor_scope.py "
        "--checker scripts/check_v011_release_successor.py"
    )
    new_scope = (
        "scripts/test_sync_import_successor_scope.py --source-root . "
        "--predecessor-root target/v011-predecessor"
    )
    if builds.count(old_scope) != 1:
        raise ValueError("expected one inherited source-scope regression invocation")
    builds = builds.replace(old_scope, new_scope, 1)
    prefix, security = builds.split("  security-gates:\n", 1)
    security, suffix = security.split("\n  app-no-ssh-e2e:\n", 1)
    rust = '          toolchain: "1.91.1"\n'
    components = "          components: rust-src\n\n"
    audit = "      - name: Install cargo-audit\n"
    if (
        any(security.count(anchor) != 1 for anchor in (rust, components, audit))
        or not security.index(rust) < security.index(components) < security.index(audit)
    ):
        raise ValueError("review changed Rust setup before preparing additive formatting checks")
    step = (
        "      - name: Sync and import successor formatting gates\n"
        "        run: |\n"
        "          set -euo pipefail\n"
        + "".join(
            f"          python3 -I -B scripts/check_sync_import_formatting.py --manifest {manifest}\n"
            for manifest in ("workspace", "htlc", "proof-backend")
        )
        + "\n"
    )
    security = security.replace(
        components, "          components: rust-src, rustfmt\n\n" + step, 1
    )
    return prefix + "  security-gates:\n" + security + "\n  app-no-ssh-e2e:\n" + suffix


def adapt_version_only_successor(builds: str) -> str:
    """Make only the reviewed checker substitution, preserving every other step."""
    old = "scripts/check_private_spend_launch_authorization.py --require-authorized"
    new = ("scripts/check_v011_release_successor.py --require-authorized "
           "--predecessor-root target/v011-predecessor")
    if builds.count(old) != 5:
        raise ValueError("expected one source and four artifact authorization checks")
    # Insert a bounded, authenticated predecessor restoration directly before each
    # authorization step. Windows keeps its existing explicit bash shell.
    lines = builds.splitlines(keepends=True)
    for index in reversed([i for i, line in enumerate(lines) if old in line]):
        start = index - 1
        while start >= 0 and not lines[start].startswith("      - name: "):
            start -= 1
        if start < 0:
            raise ValueError("authorization check must be a named canonical step")
        is_windows = "        shell: bash\n" in lines[start:index]
        materializer = (
            "      - name: Restore authenticated unchanged v0.11 predecessor\n"
            + ("        shell: bash\n" if is_windows else "")
            + "        run: python3 -I -B scripts/materialize_v011_predecessor.py "
            "--destination target/v011-predecessor --reserve-bytes 4294967296\n\n"
        )
        if "--artifact-manifest " not in lines[index]:
            materializer += (
                "      - name: Current successor scope rejection controls\n"
                "        run: python3 -I -B scripts/tests/v011_current_successor/test_successor_scope.py --checker scripts/check_v011_release_successor.py\n\n"
                "      - name: Current successor final-consumer rejection controls\n"
                "        run: python3 -I -B scripts/tests/v011_current_successor/test_successor_consumer.py --consumer scripts/check_release_crypto_profile.py --receipt-fixture scripts/tests/v011_current_successor/synthetic-final-receipt.json --artifact-manifest scripts/tests/v011_current_successor/synthetic-artifact-manifest.json --registry scripts/tests/v011_current_successor/synthetic-historical-registry.json\n\n"
                "      - name: Current security-audit scope rejection controls\n"
                "        run: python3 -I -B scripts/tests/v011_current_successor/test_security_audit_scope.py --audit-script scripts/security-audit.sh\n\n"
                "      - name: Current artifact-gate identity rejection controls\n"
                "        run: python3 -I -B scripts/tests/v011_current_successor/test_artifact_gate_identity.py --checker scripts/check_v011_release_successor.py --artifact-helper scripts/release_artifact_manifest.py --launcher-helper scripts/check_release_launcher_policy.py\n\n"
                "      - name: Current-binary proof-runner rejection controls\n"
                "        run: python3 -I -B scripts/test_check_v011_current_binary_proofs.py\n\n"
            )
        line = lines[index].replace(old, new, 1)
        if "--artifact-manifest " in line:
            line = line.rstrip("\n") + " --require-final-artifact\n"
        lines[index] = line
        lines.insert(start, materializer)
    return "".join(lines)


def adapt_pr_formal_scope(builds: str) -> str:
    """Defer only exhaustive formal steps during PR artifact preparation."""
    prefix, security = builds.split("  security-gates:\n", 1)
    security, suffix = security.split("\n  app-no-ssh-e2e:\n", 1)
    for before, after in (
        (
            "      - name: Install Lean toolchain manager\n",
            "      - name: Install Lean toolchain manager\n"
            "        if: github.event_name != 'pull_request'\n",
        ),
        (
            "      - name: Formal-core release gate\n"
            "        run: bash scripts/check_formal_core.sh\n",
            "      - name: Formal-core checker controls for PR review\n"
            "        if: github.event_name == 'pull_request'\n"
            "        run: bash scripts/check_formal_core.sh checker\n\n"
            "      - name: Formal-core policy checks for PR review\n"
            "        if: github.event_name == 'pull_request'\n"
            "        run: bash scripts/check_formal_core.sh policy\n\n"
            "      - name: Formal-core release gate\n"
            "        if: github.event_name != 'pull_request'\n"
            "        run: bash scripts/check_formal_core.sh\n",
        ),
        (
            "      - name: Complete formal cryptography release gate\n",
            "      - name: Complete formal cryptography release gate\n"
            "        if: github.event_name != 'pull_request'\n",
        ),
    ):
        if security.count(before) != 1:
            raise ValueError("review changed security formal steps before preparing")
        security = security.replace(before, after, 1)
    return prefix + "  security-gates:\n" + security + "\n  app-no-ssh-e2e:\n" + suffix


def expected_workflow(release: str) -> str:
    if release.count("\njobs:\n") != 1:
        raise ValueError("release workflow must have one canonical jobs block")
    jobs = release.split("\njobs:\n", 1)[1]
    if jobs.count("\n  create-release:\n") != 1:
        raise ValueError("release publication job must have its canonical name")
    builds, _publication = jobs.split("\n  create-release:\n", 1)
    names = tuple(re.findall(r"(?m)^  ([A-Za-z0-9_-]+):$", builds))
    if names != BUILD_JOBS:
        raise ValueError(f"review new release job set before preparing: {names!r}")
    marker = "  transaction-proof-authorization:\n"
    builds = builds.replace(marker, marker + "    needs: preparation-policy\n", 1)
    builds = adapt_version_only_successor(builds)
    builds = adapt_sync_import_release_binding(builds)
    builds = adapt_pr_formal_scope(builds)
    builds = adapt_transport_regressions(builds)
    builds = adapt_known_loser_regressions(builds)
    builds = adapt_sync_import_regressions(builds)
    output = HEADER + builds.rstrip() + "\n" + ASSEMBLE
    return "\n".join(line.rstrip() for line in output.splitlines()) + "\n"


def verify_preparation(release: str, preparation: str) -> None:
    expected = expected_workflow(release)
    if preparation != expected:
        diff = "".join(difflib.unified_diff(
            preparation.splitlines(keepends=True),
            expected.splitlines(keepends=True),
            fromfile="preparation workflow", tofile="required preparation workflow",
        ))
        raise ValueError(
            "preparation workflow differs from the reviewed release gates; "
            "review changes and regenerate with --write\n" + diff
        )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--write", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    release = (root / ".github/workflows/release.yml").read_text(encoding="utf-8")
    output = root / ".github/workflows/prepare-premainnet-release.yml"
    try:
        if args.write:
            output.write_text(expected_workflow(release), encoding="utf-8")
            print(f"Generated {output.relative_to(root)}; tag workflow unchanged")
        else:
            verify_preparation(release, output.read_text(encoding="utf-8"))
            print("Preparation preserves all seven jobs, runtime and final artifact replay; PR exhaustive formal checks deferred; non-PR full gates retained; publication absent")
    except (OSError, ValueError) as error:
        raise SystemExit(str(error)) from error


if __name__ == "__main__":
    main()
