#!/usr/bin/env python3
"""Preserve every reviewed release gate and add standalone v0.11 successor checks.

The original common authorization commands remain required. The v0.11 version-only
source and final artifact checks are additional gates, not substitutes. Removing
the original fixed-identity commands requires a separately approved transition.
Smoke-only successor results cannot assemble release assets. Publication remains
in the unchanged tag workflow.
"""

from __future__ import annotations

import argparse
import difflib
from pathlib import Path
import re

HEADER = """# Generated by scripts/prepare_premainnet_release.py --write.
# Keep release.yml and its reviewed publication policy unchanged.
name: Prepare pre-mainnet release

on:
  pull_request:
    branches: [ main ]
  workflow_dispatch:

concurrency:
  group: prepare-premainnet-${{ github.ref }}
  cancel-in-progress: true

env:
  CARGO_TERM_COLOR: always
  CARGO_NET_RETRY: "10"
  CARGO_HTTP_TIMEOUT: "600"

permissions:
  contents: read

jobs:
  preparation-policy:
    runs-on: ubuntu-24.04
    timeout-minutes: 5
    steps:
      - uses: actions/checkout@34e114876b0b11c390a56381ad16ebd13914f8d5
        with:
          persist-credentials: false
      - name: Verify preparation preserves every release build gate
        run: /usr/bin/python3 -I -B scripts/prepare_premainnet_release.py --check
      - name: Preparation workflow regression controls
        run: /usr/bin/python3 -I -B scripts/prepare_premainnet_release_test.py
      - name: v0.11 launcher boundary regressions without live peers
        run: /usr/bin/python3 -I -B scripts/test_premainnet_launcher.py
      - name: Bounded predecessor archive rejection controls
        run: /usr/bin/python3 -I -B scripts/test_materialize_v011_predecessor.py

"""
ASSEMBLE = """
  assemble-prepared-release:
    needs: [build-linux, build-macos-intel, build-macos-arm, build-windows]
    runs-on: ubuntu-latest
    timeout-minutes: 10
    steps:
      - uses: actions/checkout@34e114876b0b11c390a56381ad16ebd13914f8d5
        with:
          persist-credentials: false
      - name: Download all prepared binaries
        uses: actions/download-artifact@d3f86a106a0bac45b974a628896c90dbdf5c8093
        with:
          path: artifacts
      - name: Verify and assemble manifest-bound release assets
        run: /usr/bin/python3 -I -B scripts/release_artifact_manifest.py assemble --bundle-manifest artifacts/linux-binary/hegemon-release-assets-linux-x86_64.json --bundle-manifest artifacts/macos-intel-binary/hegemon-release-assets-macos-x86_64.json --bundle-manifest artifacts/macos-arm-binary/hegemon-release-assets-macos-arm64.json --bundle-manifest artifacts/windows-binary/hegemon-release-assets-windows-x86_64.json --output-dir release-assets
      - name: Retain prepared files for operator review
        uses: actions/upload-artifact@ea165f8d65b6e75b540449e92b4886f43607fa02
        with:
          name: premainnet-release-assets
          path: release-assets/
          if-no-files-found: error
          retention-days: 14
"""
BUILD_JOBS = (
    "transaction-proof-authorization",
    "security-gates",
    "app-no-ssh-e2e",
    "build-linux",
    "build-macos-intel",
    "build-macos-arm",
    "build-windows",
)


def adapt_version_only_successor(builds: str) -> str:
    """Add independent successor checks without replacing inherited authority."""
    old = "scripts/check_private_spend_launch_authorization.py --require-authorized"
    new = ("scripts/check_v011_release_successor.py --require-authorized "
           "--predecessor-root target/v011-predecessor")
    if builds.count(old) != 5:
        raise ValueError("expected one source and four artifact authorization checks")
    # Insert a bounded, authenticated predecessor restoration directly before each
    # authorization step. Windows keeps its existing explicit bash shell.
    lines = builds.splitlines(keepends=True)
    for index in reversed([i for i, line in enumerate(lines) if old in line]):
        start = index - 1
        while start >= 0 and not lines[start].startswith("      - name: "):
            start -= 1
        if start < 0:
            raise ValueError("authorization check must be a named canonical step")
        is_windows = "        shell: bash\n" in lines[start:index]
        materializer = (
            "      - name: Restore authenticated unchanged v0.11 predecessor\n"
            + ("        shell: bash\n" if is_windows else "")
            + "        run: python3 -I -B scripts/materialize_v011_predecessor.py "
            "--destination target/v011-predecessor --reserve-bytes 4294967296\n\n"
        )
        line = lines[index].replace(old, new, 1)
        if "--artifact-manifest " in line:
            line = line.rstrip("\n") + " --require-final-artifact\n"
        successor = (
            "\n      - name: Validate standalone v0.11 version-only successor\n"
            + ("        shell: bash\n" if is_windows else "")
            + line
        )
        lines.insert(index + 1, successor)
        lines.insert(start, materializer)
    return "".join(lines)


def expected_workflow(release: str) -> str:
    if release.count("\njobs:\n") != 1:
        raise ValueError("release workflow must have one canonical jobs block")
    jobs = release.split("\njobs:\n", 1)[1]
    if jobs.count("\n  create-release:\n") != 1:
        raise ValueError("release publication job must have its canonical name")
    builds, _publication = jobs.split("\n  create-release:\n", 1)
    names = tuple(re.findall(r"(?m)^  ([A-Za-z0-9_-]+):$", builds))
    if names != BUILD_JOBS:
        raise ValueError(f"review new release job set before preparing: {names!r}")
    marker = "  transaction-proof-authorization:\n"
    builds = builds.replace(marker, marker + "    needs: preparation-policy\n", 1)
    output = HEADER + adapt_version_only_successor(builds).rstrip() + "\n" + ASSEMBLE
    return "\n".join(line.rstrip() for line in output.splitlines()) + "\n"


def verify_preparation(release: str, preparation: str) -> None:
    expected = expected_workflow(release)
    if preparation != expected:
        diff = "".join(difflib.unified_diff(
            preparation.splitlines(keepends=True),
            expected.splitlines(keepends=True),
            fromfile="preparation workflow", tofile="required preparation workflow",
        ))
        raise ValueError(
            "preparation workflow differs from the reviewed release gates; "
            "review changes and regenerate with --write\n" + diff
        )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--write", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    release = (root / ".github/workflows/release.yml").read_text(encoding="utf-8")
    output = root / ".github/workflows/prepare-premainnet-release.yml"
    try:
        if args.write:
            output.write_text(expected_workflow(release), encoding="utf-8")
            print(f"Generated {output.relative_to(root)}; tag workflow unchanged")
        else:
            verify_preparation(release, output.read_text(encoding="utf-8"))
            print("Preparation preserves all original authorization gates and adds standalone v0.11 checks; final artifact replay required; publication absent")
    except (OSError, ValueError) as error:
        raise SystemExit(str(error)) from error


if __name__ == "__main__":
    main()
