#!/usr/bin/env python3
"""Generate and verify the nonpublishing v0.11.5 preparation workflow.

All historical security, formal, proof and platform build steps are inherited.
Only the source-selected candidate/formatting consumers change. Four exact final
qualification receipts and their original manifests are retained for packaging.

The exact candidate branch push is an authorized alternative to manual dispatch;
both run complete non-PR gates and retain Actions artifacts without publication.
"""
from __future__ import annotations

import argparse
import difflib
import importlib.util
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
WORKFLOW_PATH = '.github/workflows/prepare-premainnet-release.yml'
UPLOAD = 'actions/upload-artifact@ea165f8d65b6e75b540449e92b4886f43607fa02'
PLATFORMS = {
    'build-linux': ('linux-x86_64', 'linux-binary', 'target/release'),
    'build-macos-intel': ('macos-x86_64', 'macos-intel-binary', 'target/x86_64-apple-darwin/release'),
    'build-macos-arm': ('macos-arm64', 'macos-arm-binary', 'target/release'),
    'build-windows': ('windows-x86_64', 'windows-binary', 'target/release'),
}
WINDOWS_OWNERSHIP_COMMAND = 'python3 -I -B scripts/test_v0115_process_ownership.py --require-windows'
WINDOWS_OWNERSHIP_STEP = '''      - name: Verify native Windows process ownership before release build
        shell: bash
        run: ''' + WINDOWS_OWNERSHIP_COMMAND + '\n'
PROOF_EXECUTION_TEST_COMMAND = 'python3 -I -B scripts/test_check_v0115_current_binary_proofs.py'
PROOF_EXECUTION_TEST_STEP = '''      - name: Verify v0.11.5 proof execution source and attribution
        shell: bash
        run: ''' + PROOF_EXECUTION_TEST_COMMAND + '\n'


def module(relative, name):
    spec = importlib.util.spec_from_file_location(name, ROOT / relative)
    if spec is None or spec.loader is None:
        raise ValueError('source preparation helper unavailable: ' + relative)
    out = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(out)
    return out


historical = module('scripts/prepare_premainnet_release.py', 'v0115_historical_workflow')
packager = module('scripts/package_v0115_release.py', 'v0115_preparation_packager')


def replace_exact(text, before, after, count=1):
    if text.count(before) != count:
        raise ValueError('review changed preparation anchor before adapting: ' + before)
    return text.replace(before, after)


def expected_workflow(release):
    workflow = historical.expected_workflow(release, v0113=True, combined=True)
    workflow = replace_exact(workflow, '# Generated by scripts/prepare_premainnet_release.py --write.',
                             '# Generated by scripts/prepare_v0115_release.py --write.')
    workflow = replace_exact(workflow, '  workflow_dispatch:\n',
                             '  workflow_dispatch:\n  push:\n    branches: [ ' + packager.CANDIDATE_BRANCH + ' ]\n')
    workflow = replace_exact(workflow, 'scripts/prepare_premainnet_release.py --check --combined-candidate',
                             'scripts/prepare_v0115_release.py --check')
    workflow = replace_exact(workflow, 'scripts/check_combined_upgrade_candidate.py',
                             'scripts/check_ntime_rolling_candidate.py', 5)
    workflow = replace_exact(workflow, 'scripts/test_check_combined_upgrade_candidate.py',
                             'scripts/test_check_ntime_rolling_candidate.py', 4)
    workflow = replace_exact(workflow, 'scripts/check_combined_candidate_formatting.py',
                             'scripts/check_ntime_candidate_formatting.py', 3)
    anchor = '        run: /usr/bin/python3 -I -B scripts/prepare_premainnet_release_test.py\n'
    workflow = replace_exact(workflow, anchor, anchor + '''      - name: v0.11.5 preparation routing and evidence controls
        run: /usr/bin/python3 -I -B scripts/test_prepare_v0115_release.py
      - name: v0.11.5 exact provenance and packaging controls
        run: /usr/bin/python3 -I -B scripts/test_package_v0115_release.py
      - name: v0.11.5 proof execution source and attribution controls
        run: /usr/bin/python3 -I -B scripts/test_check_v0115_current_binary_proofs.py
''')
    for job, (selected, artifact, directory) in PLATFORMS.items():
        marker = f'  {job}:\n'
        prefix, block = workflow.split(marker, 1)
        parts = re.split(r'\n(?=  [a-z0-9-]+:\n)', block, maxsplit=1)
        body, suffix = parts[0], '\n' + parts[1] if len(parts) == 2 else ''
        if job == 'build-windows':
            # Run the actual native process-containment regression before
            # installing dependencies or beginning an expensive Cargo build.
            anchor = '      - name: Install LLVM\n'
            body = replace_exact(body, anchor, WINDOWS_OWNERSHIP_STEP + '\n'
                                 + PROOF_EXECUTION_TEST_STEP + '\n' + anchor)
        command = (f'python3 -I -B scripts/check_ntime_rolling_candidate.py --require-authorized '
                   f'--predecessor-root target/v011-predecessor --artifact-manifest '
                   f'{directory}/hegemon-release-artifacts.json --require-final-artifact')
        receipt = f'{directory}/{packager.qualification_name(selected)}'
        body = replace_exact(body, '        run: ' + command + '\n',
                             '        run: ' + command + ' > ' + receipt + '\n')
        anchor = (f'      - uses: {UPLOAD}\n        with:\n'
                  f'          name: {artifact}\n          path: release/\n')
        evidence = (f'\n      - name: Retain exact final qualification and original manifest\n'
                    f'        uses: {UPLOAD}\n        with:\n'
                    f'          name: v0115-final-{selected}\n          path: |\n'
                    f'            {receipt}\n            {directory}/hegemon-release-artifacts.json\n'
                    f'          if-no-files-found: error\n          retention-days: 14\n')
        complete = re.findall(re.escape(anchor) + r'(?:          [a-z][a-z-]*: [^\n]*\n)*', body + '\n')
        if len(complete) != 1:
            raise ValueError('review changed complete artifact upload step: ' + artifact)
        body = replace_exact(body + '\n', complete[0], complete[0] + evidence).rstrip('\n')
        workflow = prefix + marker + body + suffix
    # Generated data must remain outside the source inventory. The immutable
    # artifact verifier includes untracked, nonignored files in its tree digest.
    prefix, assemble = workflow.split('  assemble-prepared-release:\n', 1)
    assemble = replace_exact(assemble, '          path: artifacts\n', '          path: target/prepared-artifacts\n')
    assemble = replace_exact(assemble, '--bundle-manifest artifacts/', '--bundle-manifest target/prepared-artifacts/', 4)
    assemble = replace_exact(assemble, '--output-dir release-assets\n', '--output-dir target/prepared-release-assets\n')
    assemble = replace_exact(assemble, '          path: release-assets/\n', '          path: target/prepared-release-assets/\n')
    anchor = '      - name: Retain prepared files for operator review\n'
    assemble = replace_exact(assemble, anchor, '''      - name: Verify and retain manifest-bound final qualification records
        run: /usr/bin/python3 -I -B scripts/prepare_v0115_release.py --collect-qualification --artifacts target/prepared-artifacts --assets target/prepared-release-assets --output target/v0115-preparation-evidence
      - name: Retain exact qualification receipts and original manifests
        uses: ''' + UPLOAD + '''
        with:
          name: v0115-preparation-evidence
          path: target/v0115-preparation-evidence/
          if-no-files-found: error
          retention-days: 14
''' + anchor)
    return prefix + '  assemble-prepared-release:\n' + assemble


def verify_preparation(release, preparation):
    expected = expected_workflow(release)
    if preparation != expected:
        diff = ''.join(difflib.unified_diff(preparation.splitlines(keepends=True),
                expected.splitlines(keepends=True), fromfile='preparation workflow',
                tofile='required v0.11.5 preparation workflow'))
        raise ValueError('v0.11.5 preparation differs from inherited release gates; review and regenerate\n' + diff)


def collect_qualification(artifacts, assets, output):
    """Validate all inputs before exclusively creating retained evidence files."""
    receipts, originals, manifests = {}, {}, {}
    for _job, (selected, _artifact, _directory) in PLATFORMS.items():
        raw_asset = packager.base.join.checked_bytes(assets, f'hegemon-release-assets-{selected}.json')
        manifest = json.loads(raw_asset.decode('utf-8'), object_pairs_hook=packager.base.join.unique_object)
        triple = packager.base.PLATFORMS[selected][0]
        if manifest.get('target_triple') != triple or manifest.get('cargo_lock_sha256') != packager.LOCK_SHA256:
            raise ValueError('assembled platform identity differs: ' + selected)
        evidence = artifacts / ('v0115-final-' + selected)
        raw_original = packager.base.join.checked_bytes(evidence, 'hegemon-release-artifacts.json')
        original = json.loads(raw_original.decode('utf-8'), object_pairs_hook=packager.base.join.unique_object)
        if packager.base.sha(raw_original) != manifest.get('source_manifest_sha256'):
            raise ValueError('retained original artifact manifest digest differs: ' + selected)
        for field in ('source_head', 'source_index_tree', 'source_tree_sha256', 'cargo_lock_sha256', 'target_triple'):
            if original.get(field) != manifest.get(field):
                raise ValueError('original and packaged artifact source identity differs: ' + selected)
        actual = original.get('artifacts', [])
        if (not isinstance(actual, list) or len(actual) != 4
                or [(r.get('package'), r.get('binary')) for r in actual]
                   != [('hegemon-node', 'hegemon-node'), ('wallet', 'wallet'), ('walletd', 'walletd'), ('wallet', 'private-spend')]
                or {r['binary']: r.get('sha256') for r in actual}
                   != {r['binary']: r.get('sha256') for r in manifest.get('assets', [])}):
            raise ValueError('retained original binary inventory differs: ' + selected)
        receipts[selected] = packager.base.join.checked_bytes(evidence, packager.qualification_name(selected), 16 * 1024 * 1024)
        originals[selected] = raw_original
        manifests[selected] = (manifest, raw_asset)
    # The packager checks the exact proof/H0/lifecycle predicates and authority
    # boundaries. Use an isolated temporary input directory before output exists.
    import tempfile
    with tempfile.TemporaryDirectory(prefix='v0115-qualification-check-') as temporary:
        scratch = Path(temporary).resolve()
        source_manifests = scratch / 'source-manifests'
        source_manifests.mkdir()
        for selected in receipts:
            (source_manifests / f'hegemon-release-artifacts-{selected}.json').write_bytes(originals[selected])
        receipt_directory = scratch / 'receipts'
        receipt_directory.mkdir()
        for selected, raw in receipts.items():
            (receipt_directory / packager.qualification_name(selected)).write_bytes(raw)
        pins = packager.qualification_receipts(receipt_directory, manifests, ROOT, source_manifests)
    output.mkdir(parents=True, exist_ok=False)
    receipt_dir, manifest_dir = output / 'qualification-receipts', output / 'source-artifact-manifests'
    receipt_dir.mkdir()
    manifest_dir.mkdir()
    for selected in receipts:
        with (receipt_dir / packager.qualification_name(selected)).open('xb') as stream:
            stream.write(receipts[selected])
        with (manifest_dir / f'hegemon-release-artifacts-{selected}.json').open('xb') as stream:
            stream.write(originals[selected])
    return {'schema': 'hegemon.v0115.preparation-evidence.v1',
            'qualification_receipts_sha256': pins, 'publication_authorized': False,
            'deployment_authorized': False, 'physical_asic_qualified': False}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument('--check', action='store_true')
    mode.add_argument('--write', action='store_true')
    mode.add_argument('--collect-qualification', action='store_true')
    parser.add_argument('--artifacts', type=Path)
    parser.add_argument('--assets', type=Path)
    parser.add_argument('--output', type=Path)
    args = parser.parse_args(argv)
    try:
        if args.collect_qualification:
            if any(value is None for value in (args.artifacts, args.assets, args.output)):
                raise ValueError('qualification collection requires --artifacts, --assets and --output')
            print(json.dumps(collect_qualification(args.artifacts, args.assets, args.output), sort_keys=True))
        else:
            if any(value is not None for value in (args.artifacts, args.assets, args.output)):
                raise ValueError('artifact paths are only valid with --collect-qualification')
            release = (ROOT / '.github/workflows/release.yml').read_text(encoding='utf-8')
            path = ROOT / WORKFLOW_PATH
            if args.write:
                path.write_text(expected_workflow(release), encoding='utf-8')
            else:
                verify_preparation(release, path.read_text(encoding='utf-8'))
            print('v0.11.5 preparation: PASS; all inherited release gates retained; no publication')
        return 0
    except (OSError, ValueError, RuntimeError, KeyError, TypeError) as error:
        print('v0.11.5 preparation rejected: ' + str(error), file=sys.stderr)
        return 1


if __name__ == '__main__':
    raise SystemExit(main())
