def check_st2_counterexample() -> dict[str, int]:
    coefficients = [0, P - 1, 1]
    s0 = coefficients[0] % P
    s1 = sum(coefficients) % P
    printed_st2 = coefficients[1] % P
    repaired_pow1 = sum(coefficients) % P
    if (s0, s1, printed_st2, repaired_pow1) != (0, 0, P - 1, 0):
        raise AssertionError("st2 counterexample arithmetic")
    return {"printed_dot": printed_st2, "repaired_pow1_dot": repaired_pow1, "s_at_0": s0, "s_at_1": s1}


def emit() -> None:
    manifest = build_manifest()
