def check_closed_form_bijection(spec: CarrierSpec = PRODUCTION_SPEC) -> dict[str, Any]:
    spec.validate()
    boundaries = [0, 1, spec.source_l, spec.source_l + 1, spec.source_n]
    for column in boundaries:
        mapped = map_source_column(column, spec)
        if unmap_source_column(mapped, spec) != column:
            raise AssertionError((column, mapped))
    source_segment_count = 1 + spec.source_l + spec.witness_used
    if source_segment_count != spec.source_n + 1:
        raise AssertionError("source column segment partition")
    public_image = (0, spec.source_l + 1)
    witness_image = (spec.ell, spec.ell + spec.witness_used)
    if public_image[1] > witness_image[0] or witness_image[1] > spec.side:
        raise AssertionError("mapped column segments overlap or overflow")
    for padding_column in (spec.source_l + 1, spec.ell - 1, spec.ell + spec.witness_used, spec.side - 1):
        try:
            unmap_source_column(padding_column, spec)
        except ValueError:
            pass
        else:
            raise AssertionError(("padding inverse accepted", padding_column))
    embedded_nnz = spec.source_nnz + 2 * spec.witness_padding
    if spec is PRODUCTION_SPEC and embedded_nnz != EMBEDDED_NNZ:
        raise AssertionError("frozen embedded nnz equation")
    return {
        "carrier_side": spec.side,
        "column_domain": spec.source_n + 1,
        "mapped_source_nnz": spec.source_nnz,
        "padding_nnz": 2 * spec.witness_padding,
    }


def expect_reject(name: str, fn: Any) -> str:
    try:
        fn()
    except (AssertionError, TypeError, ValueError):
        return name
    raise AssertionError(f"mutation accepted: {name}")


