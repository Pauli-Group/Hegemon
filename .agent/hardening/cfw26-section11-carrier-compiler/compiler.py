def canonical_bytes(value: Any) -> bytes:
    return (json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=False) + "\n").encode()


def sha512_bytes(data: bytes) -> str:
    return hashlib.sha512(data).hexdigest()


def sha512_file(path: Path) -> str:
    return sha512_bytes(path.read_bytes())


def shake_digest(domain: bytes, payload: bytes) -> str:
    return hashlib.shake_256(domain + len(payload).to_bytes(8, "big") + payload).hexdigest(64)


def reject_duplicate_keys(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
    result: dict[str, Any] = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"duplicate JSON key: {key}")
        result[key] = value
    return result


def parse_canonical_json_bytes(raw: bytes, *, max_bytes: int) -> Any:
    if not isinstance(raw, bytes):
        raise TypeError("parser accepts immutable bytes only")
    if not raw or len(raw) > max_bytes:
        raise ValueError("JSON byte length outside exact parser bound")
    try:
        text = raw.decode("utf-8", "strict")
        value = json.loads(text, object_pairs_hook=reject_duplicate_keys)
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise ValueError("invalid canonical JSON") from exc
    if canonical_bytes(value) != raw:
        raise ValueError("noncanonical JSON bytes")
    return value


def parse_canonical_json_file(path: Path, *, exact_bytes: int) -> Any:
    raw = path.read_bytes()
    if len(raw) != exact_bytes:
        raise ValueError(f"unexpected byte length for {path}")
    return parse_canonical_json_bytes(raw, max_bytes=exact_bytes)


def encode_coefficient(value: int) -> str:
    if not isinstance(value, int) or isinstance(value, bool) or not (0 < value < P):
        raise ValueError("sparse coefficient must be canonical and nonzero")
    return value.to_bytes(FIELD_BYTES, "little").hex()


def decode_coefficient(encoded: str) -> int:
    if not isinstance(encoded, str) or len(encoded) != 2 * FIELD_BYTES:
        raise ValueError("coefficient must be exactly eight encoded bytes")
    if encoded.lower() != encoded or any(ch not in "0123456789abcdef" for ch in encoded):
        raise ValueError("coefficient must be lowercase hexadecimal")
    value = int.from_bytes(bytes.fromhex(encoded), "little")
    if not (0 < value < P):
        raise ValueError("zero or noncanonical coefficient")
    return value


@dataclass(frozen=True, order=True)
class SparseEntry:
    """One nonzero in A, B, or C.

    Ordering is supplied separately because the paper/source convention is
    row, then A/B/C, then strictly increasing column.
    """

    matrix: str
    row: int
    column: int
    coefficient: int

    def as_json(self) -> dict[str, Any]:
        return {
            "coefficient_le_hex": encode_coefficient(self.coefficient),
            "column": self.column,
            "matrix": self.matrix,
            "row": self.row,
        }


def entry_key(entry: SparseEntry) -> tuple[int, int, int]:
    if entry.matrix not in MATRIX_ORDER:
        raise ValueError("matrix must be A, B, or C")
    return entry.row, MATRIX_ORDER[entry.matrix], entry.column


@dataclass(frozen=True)
class CarrierSpec:
    source_m: int = SOURCE_M
    source_n: int = SOURCE_N
    source_l: int = SOURCE_L
    source_nnz: int = SOURCE_NNZ
    ell: int = ELL

    @property
    def witness_used(self) -> int:
        return self.source_n - self.source_l

    @property
    def side(self) -> int:
        return 2 * self.ell

    @property
    def public_padding(self) -> int:
        return self.ell - (self.source_l + 1)

    @property
    def witness_padding(self) -> int:
        return self.ell - self.witness_used

    @property
    def witness_zero_end(self) -> int:
        return self.source_m + self.witness_padding

    @property
    def zero_rows(self) -> int:
        return self.side - self.witness_zero_end

    def validate(self) -> None:
        if self.source_l < 0 or self.source_m < 0 or self.source_n < self.source_l:
            raise ValueError("invalid source geometry")
        if self.ell <= 0 or self.ell & (self.ell - 1):
            raise ValueError("ell must be a positive power of two")
        if self.source_l + 1 > self.ell or self.witness_used > self.ell:
            raise ValueError("source does not fit equal halves")
        if self.witness_zero_end > self.side:
            raise ValueError("padding constraints do not fit square carrier")
        if self.source_nnz < 0:
            raise ValueError("negative source nonzero count")


