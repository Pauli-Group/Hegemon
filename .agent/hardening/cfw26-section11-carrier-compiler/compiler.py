    if not isinstance(geometry, dict) or set(geometry) != {
        "ell",
        "matrix_nonzeros_total",
        "m_constraints",
        "n_nonconstant_variables",
        "public_variables",
    }:
        raise ValueError("tiny fixture geometry schema mismatch")
    if any(not isinstance(geometry[key], int) or isinstance(geometry[key], bool) for key in geometry):
        raise ValueError("tiny fixture geometry type mismatch")
