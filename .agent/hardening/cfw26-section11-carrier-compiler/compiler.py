    if value["field_modulus_decimal"] != str(P):
        raise ValueError("tiny fixture field mismatch")
    body = {key: value[key] for key in value if key != "relation_digest_shake256_512"}
    digest = shake_digest(b"hegemon.cfw26.section11.carrier-map.tiny-r1cs.v1\0", canonical_bytes(body))
    if value["relation_digest_shake256_512"] != digest:
        raise ValueError("tiny fixture relation digest mismatch")
