def next_power_of_two(value: int) -> int:
    if not isinstance(value, int) or isinstance(value, bool) or value <= 0:
        raise ValueError("power-of-two input must be positive integer")
    return 1 << (value - 1).bit_length()


def derive_equal_half_spec(*, m: int, n: int, l: int, nnz: int) -> CarrierSpec:
    """Derive the smallest power-of-two half for this exact padding schedule.

    Besides fitting the public and witness halves, `ell >= m-(n-l)` is needed
    because every unused witness coordinate consumes one row after all source
    rows.  This is stronger and more directly tied to the chosen schedule than
    merely requiring `2*ell >= m`.
    """
    for name, value in (("m", m), ("n", n), ("l", l), ("nnz", nnz)):
        if not isinstance(value, int) or isinstance(value, bool):
            raise ValueError(f"{name} must be an integer")
    if m < 0 or n < 0 or l < 0 or nnz < 0 or l > n:
        raise ValueError("invalid parameterized source geometry")
    witness = n - l
    lower_bound = max(1, l + 1, witness, m - witness)
    spec = CarrierSpec(source_m=m, source_n=n, source_l=l, source_nnz=nnz, ell=next_power_of_two(lower_bound))
    spec.validate()
    return spec


def validate_relation_digest(digest: str) -> str:
    if (
        not isinstance(digest, str)
        or len(digest) != 128
        or digest.lower() != digest
        or any(ch not in "0123456789abcdef" for ch in digest)
    ):
        raise ValueError("source relation digest must be canonical 64-byte lowercase hex")
    if int(digest, 16) == 0:
        raise ValueError("source relation digest must be nonzero")
    return digest


