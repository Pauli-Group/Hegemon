def map_source_column(column: int, spec: CarrierSpec = PRODUCTION_SPEC) -> int:
    spec.validate()
    if not isinstance(column, int) or isinstance(column, bool) or not (0 <= column <= spec.source_n):
        raise ValueError("source column outside z")
    if column <= spec.source_l:
        return column
    return spec.ell + column - (spec.source_l + 1)


def unmap_source_column(column: int, spec: CarrierSpec = PRODUCTION_SPEC) -> int:
    spec.validate()
    if not isinstance(column, int) or isinstance(column, bool):
        raise ValueError("embedded column must be an integer")
    if 0 <= column <= spec.source_l:
        return column
    witness_end = spec.ell + spec.witness_used
    if spec.ell <= column < witness_end:
        return spec.source_l + 1 + column - spec.ell
    raise ValueError("embedded column is padding or outside source image")


def validate_source_entry(entry: SparseEntry, spec: CarrierSpec = PRODUCTION_SPEC) -> None:
    if entry.matrix not in MATRIX_ORDER:
        raise ValueError("invalid source matrix")
    if not (0 <= entry.row < spec.source_m):
        raise ValueError("source row outside source relation")
    map_source_column(entry.column, spec)
    encode_coefficient(entry.coefficient)


def map_source_entry(entry: SparseEntry, spec: CarrierSpec = PRODUCTION_SPEC) -> SparseEntry:
    validate_source_entry(entry, spec)
    return replace(entry, column=map_source_column(entry.column, spec))


def unmap_source_entry(entry: SparseEntry, spec: CarrierSpec = PRODUCTION_SPEC) -> SparseEntry:
    if entry.matrix not in MATRIX_ORDER or not (0 <= entry.row < spec.source_m):
        raise ValueError("entry is not in mapped source row image")
    encode_coefficient(entry.coefficient)
    source = replace(entry, column=unmap_source_column(entry.column, spec))
    validate_source_entry(source, spec)
    return source


def validate_mapped_pair(source: SparseEntry, mapped: SparseEntry, spec: CarrierSpec = PRODUCTION_SPEC) -> None:
    if map_source_entry(source, spec) != mapped:
        raise ValueError("mapped entry is not the exact source image")
    if unmap_source_entry(mapped, spec) != source:
        raise ValueError("mapped entry does not invert exactly")


def witness_padding_entries(index: int, spec: CarrierSpec = PRODUCTION_SPEC) -> tuple[SparseEntry, SparseEntry]:
    """Return the exact A and B nonzeros for padding equation x*1=0."""
    spec.validate()
    if not isinstance(index, int) or isinstance(index, bool) or not (0 <= index < spec.witness_padding):
        raise ValueError("witness-padding index outside schedule")
    row = spec.source_m + index
    x_column = spec.ell + spec.witness_used + index
    return SparseEntry("A", row, x_column, 1), SparseEntry("B", row, 0, 1)


def validate_padding_entry_pair(
    index: int, entries: Sequence[SparseEntry], spec: CarrierSpec = PRODUCTION_SPEC
) -> None:
    expected = witness_padding_entries(index, spec)
    if tuple(entries) != expected:
        raise ValueError("padding row must be exactly A[x]=1, B[v0]=1, C empty")


def source_stream_to_carrier(
    entries: Iterable[SparseEntry], spec: CarrierSpec = PRODUCTION_SPEC
) -> Iterator[SparseEntry]:
    """Stream source entries without buffering or changing stream identity."""
    previous: tuple[int, int, int] | None = None
    count = 0
    for entry in entries:
        key = entry_key(entry)
        if previous is not None and key <= previous:
            raise ValueError("source sparse stream is duplicated or noncanonical")
        mapped = map_source_entry(entry, spec)
        validate_mapped_pair(entry, mapped, spec)
        yield mapped
        previous = key
        count += 1
    if count != spec.source_nnz:
        raise ValueError("source sparse stream has a missing or extra nonzero")


def carrier_padding_stream(spec: CarrierSpec = PRODUCTION_SPEC) -> Iterator[SparseEntry]:
    for index in range(spec.witness_padding):
        yield from witness_padding_entries(index, spec)


def validate_public_half(values: Sequence[int], spec: CarrierSpec = PRODUCTION_SPEC) -> None:
    if len(values) != spec.ell or values[0] != 1:
        raise ValueError("public half must have ell elements and v[0]=1")
    if any(value != 0 for value in values[spec.source_l + 1 :]):
        raise ValueError("public parser padding must be exactly zero")


def validate_witness_padding(values: Sequence[int], spec: CarrierSpec = PRODUCTION_SPEC) -> None:
    if len(values) != spec.ell:
        raise ValueError("witness half must have ell elements")
    if any(value % P != 0 for value in values[spec.witness_used :]):
        raise ValueError("existential witness padding violates x*1=0")


def embed_source_assignment(source_z: Sequence[int], spec: CarrierSpec = PRODUCTION_SPEC) -> list[int]:
    spec.validate()
    if len(source_z) != spec.source_n + 1 or source_z[0] != 1:
        raise ValueError("source assignment length or constant slot mismatch")
    if any(not isinstance(value, int) or isinstance(value, bool) or not (0 <= value < P) for value in source_z):
        raise ValueError("source assignment contains noncanonical field element")
    v = list(source_z[: spec.source_l + 1]) + [0] * spec.public_padding
    w = list(source_z[spec.source_l + 1 :]) + [0] * spec.witness_padding
    validate_public_half(v, spec)
    validate_witness_padding(w, spec)
    return v + w


def eval_linear(entries: Iterable[SparseEntry], assignment: Sequence[int]) -> int:
    return sum(entry.coefficient * assignment[entry.column] for entry in entries) % P


def row_values(entries: Iterable[SparseEntry], assignment: Sequence[int], row: int) -> tuple[int, int, int]:
    lanes: dict[str, list[SparseEntry]] = {"A": [], "B": [], "C": []}
    for entry in entries:
        if entry.row == row:
            lanes[entry.matrix].append(entry)
    return tuple(eval_linear(lanes[matrix], assignment) for matrix in ("A", "B", "C"))


def row_holds(values: tuple[int, int, int]) -> bool:
    a, b, c = values
    return a * b % P == c


